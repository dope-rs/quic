#[test]
fn initial_secrets_match_rfc9001() {
    let init = Hkdf::extract(&dope_quic::qkdf::INITIAL_SALT_V1, &DCID);
    assert_eq!(init, INITIAL_SECRET);
    let s = InitialSecrets::from_dcid(&DCID);
    assert_eq!(s.client, CLIENT_SECRET);
    assert_eq!(s.server, SERVER_SECRET);
}

#[test]
fn rfc5869_a1_hkdf_extract_test_vector() {
    let ikm = [0x0bu8; 22];
    let salt: [u8; 13] = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c,
    ];
    let expected: [u8; 32] = [
        0x07, 0x77, 0x09, 0x36, 0x2c, 0x2e, 0x32, 0xdf, 0x0d, 0xdc, 0x3f, 0x0d, 0xc4, 0x7b, 0xba,
        0x63, 0x90, 0xb6, 0xc7, 0x3b, 0xb5, 0x0f, 0x9c, 0x31, 0x22, 0xec, 0x84, 0x4a, 0xd7, 0xc2,
        0xb3, 0xe5,
    ];
    let prk = Hkdf::extract(&salt, &ikm);
    eprintln!("computed = {:02x?}", prk);
    eprintln!("expected = {:02x?}", expected);
    assert_eq!(prk, expected);
}

#[test]
fn client_packet_keys_match_rfc9001() {
    let pk = PacketKeys::aes_128(&CLIENT_SECRET);
    assert_eq!(pk.key, CLIENT_KEY);
    assert_eq!(pk.iv, CLIENT_IV);
    assert_eq!(pk.hp, CLIENT_HP);
}

#[test]
fn server_packet_keys_match_rfc9001() {
    let pk = PacketKeys::aes_128(&SERVER_SECRET);
    assert_eq!(pk.key, SERVER_KEY);
    assert_eq!(pk.iv, SERVER_IV);
    assert_eq!(pk.hp, SERVER_HP);
}

#[test]
fn hp_mask_for_client_initial_sample() {
    const SAMPLE: [u8; 16] = [
        0xd1, 0xb1, 0xc9, 0x8d, 0xd7, 0x68, 0x9f, 0xb8, 0xec, 0x11, 0xd2, 0x42, 0xb1, 0x23, 0xdc,
        0x9b,
    ];
    const MASK: [u8; 5] = [0x43, 0x7b, 0x9a, 0xec, 0x36];

    let hp = HpKey::aes_128(&CLIENT_HP);
    assert_eq!(hp.mask(&SAMPLE).unwrap(), MASK);
}
